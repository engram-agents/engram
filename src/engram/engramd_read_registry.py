"""engramd_read_registry -- the tier-1 read-template registry (U4c, #3196,
part of #2652; design docs/internal/2652-security-slice-design.md SS3.2-3.5, SS5, SS7).

Stdlib only. The owner admits a client read iff the EXACT BYTES of its SQL
equal a template registered at build time. Everything else is refused, not
executed, not prepared on the connection (default-deny). The contract
(R1-R13) was posted on #3196 and is encoded in tests/test_engramd_read_registry.py
and tests/test_engramd_read_scan.py; this docstring only orients a reader.

Admission is caller-blind. ``Registry.check(sql, params)`` takes no caller
identity: a statement is admitted by its exact template bytes alone. The only
per-connection caller gate is the owner socket's same-uid peer-credential
check (the socket also sits behind uid-scoped filesystem permissions: a 0700
run/ directory with ACLs stripped). The
``sites`` field of ``engramd_read_templates.json`` is build-time provenance,
generated by ``tools/engramd_read_scan.py`` and verified against the real tree
in CI; it decides which statements get registered, never who may send one. It
is not a permission.

What this module is made of
---------------------------
* ``template_key(sql)`` -- sha256 of the UTF-8 bytes. NO normalisation (R1):
  one changed byte is a different, unregistered template.
* ``classify_template(sql, schema_conn)`` -- registration-time classification
  decided from the SCHEMA, never from operator spelling (R5-R7):

    1. the statement is tokenised by a small hand-written lexer (strings,
       quoted identifiers, comments, anonymous/named/numbered parameters);
       a construct it cannot place fails closed (R6d); named or numbered
       parameters are refused (R6c);
    2. the lexer's anonymous-``?`` count is cross-checked against the
       ENGINE's count, measured by probing ``EXPLAIN <sql>`` with 0..N bound
       values and catching the ``sqlite3.ProgrammingError`` TYPE (R6a);
    3. ``EXPLAIN <sql>`` is prepared under an AUDITING authorizer that
       records every ``SQLITE_READ``; every read is placed against
       ``sqlite_master`` (R6b): an unknown table, a non-``main`` database,
       an empty table name, or a ``json_each`` outside the one admitted form
       is unplaceable -> refused. A virtual table (or a shadow table of one:
       FTS5, vec0, rtree...) is refused outright (R5) -- this unit's answer
       to design SS7's open FTS5 policy;
    4. each ``?`` is classified by the token BEFORE it against a CLOSED safe
       set (R7); anything else needs a declared owner-side policy from
       ``PARAM_RULES`` (R8) or the template is refused.

  Registration does not judge the statement VERB: the client-read
  authorizer (U4b) is the second, independent layer (R9).
* ``PARAM_RULES`` -- the bound-parameter validator family (R8).
* ``Registry`` -- an immutable lookup; ``check(sql, params)`` returns None
  (admit) or a ``Rejected``. There is no mutating method. A ``DynamicRegistry``
  (R4, dev tier only, escape hatch named and off) additionally offers
  ``register_dynamic``.
* ``load_registry(path, schema_conn)`` -- the R12 loader: any problem with
  the committed file yields an EMPTY registry or drops the offending
  template, never a permissive one.

No log-and-allow mode exists anywhere in this module.
"""
