def template_key(sql: str) -> str:
    """R1: sha256 of the exact UTF-8 bytes. No normalisation of any kind."""
    return hashlib.sha256(sql.encode("utf-8")).hexdigest()


# ---------------------------------------------------------------------------
# Lexer (R6c, R6d, R7). Hand-written; no regex-only approach.
# ---------------------------------------------------------------------------


class _Tok(NamedTuple):
    kind: str  # word | string | qident | param | param_numbered | param_named | op
    text: str
    pos: int


_WS = " \t\n\f\r"
_MULTI_OPS = ("->>", "->", "<>", "<=", ">=", "!=", "==", "<<", ">>", "||")


def _is_ident_char(ch: str) -> bool:
    return ch.isalnum() or ch in "_$" or ord(ch) > 127


def _is_digit(ch: str) -> bool:
    return "0" <= ch <= "9"


def _tokenize(sql: str) -> List[_Tok]:
    """Tokenise ``sql``. Comments and whitespace are dropped. Raises
    ``_TokenizeError`` on an unterminated string/comment/bracket (R6d)."""
    toks: List[_Tok] = []
    i, n = 0, len(sql)
    while i < n:
        ch = sql[i]
        if ch in _WS:
            i += 1
            continue
        if ch == "-" and sql.startswith("--", i):
            j = sql.find("\n", i)
            i = n if j < 0 else j + 1
            continue
        if ch == "/" and sql.startswith("/*", i):
            j = sql.find("*/", i + 2)
            if j < 0:
                raise _TokenizeError(f"unterminated /* comment at offset {i}")
            i = j + 2
            continue
        if ch in "'\"`":
            j = i + 1
            while True:
                j = sql.find(ch, j)
                if j < 0:
                    raise _TokenizeError(f"unterminated {ch} quote at offset {i}")
                if sql.startswith(ch, j + 1):  # doubled quote = escaped quote
                    j += 2
                    continue
                break
            toks.append(_Tok("string" if ch == "'" else "qident", sql[i : j + 1], i))
            i = j + 1
            continue
        if ch == "[":
            j = sql.find("]", i + 1)
            if j < 0:
                raise _TokenizeError(f"unterminated [ bracket at offset {i}")
            toks.append(_Tok("qident", sql[i : j + 1], i))
            i = j + 1
            continue
        if ch == "?":
            j = i + 1
            while j < n and _is_digit(sql[j]):
                j += 1
            toks.append(_Tok("param_numbered" if j > i + 1 else "param", sql[i:j], i))
            i = j
            continue
        if ch in ":@$" and i + 1 < n and _is_ident_char(sql[i + 1]):
            j = i + 1
            while j < n and _is_ident_char(sql[j]):
                j += 1
            toks.append(_Tok("param_named", sql[i:j], i))
            i = j
            continue
        if _is_ident_char(ch):
            j = i + 1
            while j < n and _is_ident_char(sql[j]):
                j += 1
            toks.append(_Tok("word", sql[i:j], i))
            i = j
            continue
        for op in _MULTI_OPS:
            if sql.startswith(op, i):
                toks.append(_Tok("op", op, i))
                i += len(op)
                break
        else:
            toks.append(_Tok("op", ch, i))
            i += 1
    return toks


def _scanner_placeholder_count(sql: str) -> int:
    """The scanner's own count of anonymous ``?`` tokens (string-, comment-,
    bracket- and quote-aware). A hook: R6a compares it with the ENGINE's
    count, and the tests monkeypatch it to force a disagreement."""
    return sum(1 for t in _tokenize(sql) if t.kind == "param")


def _exact_json_each_form_at(sql: str, qpos: int) -> bool:
    """True iff the ``?`` at ``qpos`` is the sole argument of ``json_each(``
    in the EXACT byte form ``IN (SELECT value FROM json_each(?))``."""
    start = qpos - _JSON_EACH_Q_OFFSET
    if start < 0 or sql[start : start + len(JSON_EACH_FORM)] != JSON_EACH_FORM:
        return False
    return start == 0 or not _is_ident_char(sql[start - 1])


# ---------------------------------------------------------------------------
# Engine probes (R6a, R5, R6b)
# ---------------------------------------------------------------------------

_PROBE_HEADROOM = 16


def _engine_param_count(sql: str, conn: sqlite3.Connection, scanner_count: int) -> Optional[int]:
    """R6a: the ENGINE's parameter count, measured by probing
    ``EXPLAIN <sql>`` with n = 0..N bound values until it stops raising
    ``sqlite3.ProgrammingError`` (the TYPE is the signal; the message is
    never parsed). ``None`` if no n in range works (e.g. more than one
    statement). Any other engine error (syntax, unknown table, missing
    module) propagates as ``sqlite3.Error`` for the caller to fail closed."""
    for n in range(max(scanner_count, 0) + _PROBE_HEADROOM):
        try:
            conn.execute("EXPLAIN " + sql, (None,) * n).fetchall()
        except sqlite3.ProgrammingError:
            continue
        return n
    return None


def _audit_reads(sql: str, conn: sqlite3.Connection) -> List[Tuple[Any, ...]]:
    """R5(i): prepare ``EXPLAIN <sql>`` on ``conn`` under an AUDITING
    authorizer (allow-all, records only) and return every ``SQLITE_READ`` as
    a ``(table, column, db_name, trigger_or_view)`` tuple, de-duplicated,
    in first-seen order.

    ``conn`` must be a DEDICATED schema connection: this helper installs an
    authorizer and leaves the connection with NO authorizer afterwards.
    Raises ``sqlite3.Error`` if the engine cannot prepare the statement."""
    events: List[Tuple[Any, ...]] = []

    def _auditor(action, arg1, arg2, db_name, trigger_or_view):
        if action == sqlite3.SQLITE_READ:
            events.append((arg1, arg2, db_name, trigger_or_view))
        return sqlite3.SQLITE_OK

    count = _engine_param_count(sql, conn, _scanner_placeholder_count(sql))
    if count is None:
        raise sqlite3.ProgrammingError("no parameter count satisfies the engine")
    events.clear()  # the probe itself may have audited failed attempts
    conn.set_authorizer(_auditor)
    try:
        conn.execute("EXPLAIN " + sql, (None,) * count).fetchall()
    finally:
        conn.set_authorizer(None)
    seen = set()
    out: List[Tuple[Any, ...]] = []
    for ev in events:
        if ev not in seen:
            seen.add(ev)
            out.append(ev)
    return out


def _incomplete(detail: str) -> Rejected:
    return Rejected(
        reason="classification_incomplete",
        detail=detail,
        remedy="the classifier could not account for every part of this statement; "
        "rewrite it to a form it can classify, or use a typed read operation",
    )


def _schema_catalog(conn: sqlite3.Connection) -> Tuple[Dict[str, Tuple[str, str]], set, set]:
    """-> (main objects {lower(name): (type, sql)}, lower names of virtual
    tables, lower names that also exist in temp/attached schemas)."""
    main: Dict[str, Tuple[str, str]] = {}
    virtual = set()
    for name, typ, sql in conn.execute("SELECT name, type, sql FROM sqlite_master"):
        if typ not in ("table", "view") or name is None:
            continue
        main[name.lower()] = (typ, sql or "")
        if typ == "table" and " ".join((sql or "").split()).upper().startswith("CREATE VIRTUAL TABLE"):
            virtual.add(name.lower())
    shadowing = set()
    for name, typ in conn.execute("SELECT name, type FROM sqlite_temp_master"):
        if typ in ("table", "view") and name:
            shadowing.add(name.lower())
    for _seq, dbname, _file in conn.execute("PRAGMA database_list").fetchall():
        if dbname in ("main", "temp"):
            continue
        quoted = '"' + dbname.replace('"', '""') + '"'
        for (name,) in conn.execute(f"SELECT name FROM {quoted}.sqlite_master WHERE type IN ('table','view')"):
            if name:
                shadowing.add(name.lower())
    return main, virtual, shadowing


# ---------------------------------------------------------------------------
# R8: the bound-parameter validator family
# ---------------------------------------------------------------------------

#: R8 limit_bounded: the declared maximum for a bound LIMIT/OFFSET value.
LIMIT_MAX = 1000

#: R8 json_path_fixed: the declared allowlist of bound JSON paths. Empty: no
#: bound path is admitted (design SS3.3: a bound ``'$'`` is a probe, and no
#: tier-1 template needs a client-chosen path).
JSON_PATH_ALLOWLIST: frozenset = frozenset()


def _rule_like_escaped(value) -> None:
    """A LIKE pattern must carry no live wildcard: ``%`` and ``_`` appear
    only escaped, and a backslash only as part of ``\\\\``, ``\\%`` or
    ``\\_`` -- i.e. consistent with ``engram_filter._like_escape``."""
    if not isinstance(value, str):
        raise ParamRejected("like_escaped", "LIKE pattern must be a str")
    i, n = 0, len(value)
    while i < n:
        ch = value[i]
        if ch == "\\":
            if i + 1 >= n or value[i + 1] not in "\\%_":
                raise ParamRejected("like_escaped", "dangling or unknown escape in LIKE pattern")
            i += 2
            continue
        if ch in "%_":
            raise ParamRejected("like_escaped", "unescaped LIKE wildcard in pattern")
        i += 1


def _rule_like_escape_clause(value) -> None:
    if value != "\\" or not isinstance(value, str):
        raise ParamRejected("like_escape_clause", "ESCAPE value must be a single backslash")


def _rule_glob_literal(value) -> None:
    """A GLOB 'literal' contains none of the three live characters ``*``,
    ``?`` and ``[`` (GLOB has no escape character); everything else,
    including the empty string, is admitted."""
    if not isinstance(value, str):
        raise ParamRejected("glob_literal", "GLOB pattern must be a str")
    if any(ch in value for ch in "*?["):
        raise ParamRejected("glob_literal", "GLOB wildcard or character class is not admitted")


def _rule_json_path_fixed(value) -> None:
    if not isinstance(value, str) or value not in JSON_PATH_ALLOWLIST:
        raise ParamRejected("json_path_fixed", "bound JSON path is outside the declared allowlist")


def _rule_limit_bounded(value) -> None:
    if isinstance(value, bool) or not isinstance(value, int) or not (0 <= value <= LIMIT_MAX):
        raise ParamRejected("limit_bounded", f"LIMIT/OFFSET must be an int in [0, {LIMIT_MAX}]")


#: R8: rule name -> validator. The test module iterates THIS mapping against
#: its own case table, so a rule added here without cases fails the suite.
PARAM_RULES: Mapping[str, Callable[[Any], None]] = types.MappingProxyType(
    {
        "like_escaped": _rule_like_escaped,
        "like_escape_clause": _rule_like_escape_clause,
        "glob_literal": _rule_glob_literal,
        "json_path_fixed": _rule_json_path_fixed,
        "limit_bounded": _rule_limit_bounded,
    }
)


# ---------------------------------------------------------------------------
# R8 template contexts: a validator certifies a parameter VALUE under an
# assumption about the TEMPLATE TEXT around its placeholder (e.g. like_escaped
# assumes backslash is the LIKE escape, true only with ESCAPE '\'). Each rule
# therefore declares the token context it is valid in; _classify refuses a
# policy declared on any other placeholder (policy_template_mismatch).
# A predicate takes (toks, i, ordinal, policies): the lexer tokens, the index of
# the placeholder token, {token index -> 0-based placeholder ordinal}, and the
# declared {ordinal -> rule} policies.
# ---------------------------------------------------------------------------


def _is_word(tok, *names) -> bool:
    return tok is not None and tok.kind == "word" and tok.text.upper() in names


def _at(toks, j):
    return toks[j] if 0 <= j < len(toks) else None


def _operand_is_closed(toks, j) -> bool:
    """True when the token AFTER an operand (index ``j``) cannot extend that
    operand into an expression: end of statement, a word (AND, ORDER, ...), or
    one of ``) ; ,``. A binary operator such as ``||`` would."""
    t = _at(toks, j)
    return t is None or t.kind != "op" or t.text in (")", ";", ",")


def _ctx_like_escaped(toks, i, ordinal, policies) -> bool:
    if not _is_word(_at(toks, i - 1), "LIKE") or not _is_word(_at(toks, i + 1), "ESCAPE"):
        return False
    esc = _at(toks, i + 2)
    if esc is None:
        return False
    if esc.kind == "string":
        if esc.text[1:-1].replace("''", "'") != "\\":
            return False
    elif esc.kind == "param":
        if policies.get(ordinal.get(i + 2)) != "like_escape_clause":
            return False
    else:
        return False
    return _operand_is_closed(toks, i + 3)


def _ctx_like_escape_clause(toks, i, ordinal, policies) -> bool:
    if not _is_word(_at(toks, i - 1), "ESCAPE"):
        return False
    pat = _at(toks, i - 2)
    if pat is None or pat.kind != "param" or policies.get(ordinal.get(i - 2)) != "like_escaped":
        return False
    return _operand_is_closed(toks, i + 1)


def _ctx_glob_literal(toks, i, ordinal, policies) -> bool:
    return _is_word(_at(toks, i - 1), "GLOB") and _operand_is_closed(toks, i + 1)


def _ctx_limit_bounded(toks, i, ordinal, policies) -> bool:
    return _is_word(_at(toks, i - 1), "LIMIT", "OFFSET") and _operand_is_closed(toks, i + 1)


_NOT_A_FUNCTION = frozenset({
    "IN", "VALUES", "SELECT", "WHERE", "AND", "OR", "NOT", "ON", "FROM", "BY", "AS", "BETWEEN",
    "WHEN", "THEN", "ELSE", "CASE", "EXISTS", "USING", "HAVING", "JOIN", "UNION", "LIMIT",
    "OFFSET", "LIKE", "GLOB", "ESCAPE",
})


def _ctx_json_path_fixed(toks, i, ordinal, policies) -> bool:
    prev = _at(toks, i - 1)
    if prev is None or prev.kind != "op" or prev.text != ",":
        return False
    depth = 0
    for j in range(i - 1, -1, -1):
        t = toks[j]
        if t.kind == "op" and t.text == ")":
            depth += 1
        elif t.kind == "op" and t.text == "(":
            if depth == 0:
                name = _at(toks, j - 1)
                return name is not None and name.kind == "word" and name.text.upper() not in _NOT_A_FUNCTION
            depth -= 1
    return False


#: rule name -> predicate over the placeholder's token context. The test module
#: asserts its keys equal PARAM_RULES' keys: a rule cannot be added without
#: saying what template context it is valid in.
PARAM_RULE_CONTEXTS: Mapping[str, Callable[..., bool]] = types.MappingProxyType(
    {
        "like_escaped": _ctx_like_escaped,
        "like_escape_clause": _ctx_like_escape_clause,
        "glob_literal": _ctx_glob_literal,
        "json_path_fixed": _ctx_json_path_fixed,
        "limit_bounded": _ctx_limit_bounded,
    }
)

_CONTEXT_REQUIRES: Mapping[str, str] = types.MappingProxyType(
    {
        "like_escaped": "the placeholder to follow LIKE and be followed by ESCAPE '\\' "
        "(or ESCAPE ? declared like_escape_clause)",
        "like_escape_clause": "the placeholder to follow ESCAPE after a LIKE pattern placeholder "
        "declared like_escaped",
        "glob_literal": "the placeholder to follow GLOB",
        "json_path_fixed": "the placeholder to be a later argument of a function call",
        "limit_bounded": "the placeholder to follow LIMIT or OFFSET",
    }
)


# ---------------------------------------------------------------------------
# Classification (R5, R6, R7)
# ---------------------------------------------------------------------------


def classify_template(
    sql: str,
    schema_conn: sqlite3.Connection,
    param_policies: Optional[Mapping[int, str]] = None,
) -> Optional[Rejected]:
    """Classify ``sql`` for registration against ``schema_conn``'s schema.
    Returns None when the template may be registered, else the ``Rejected``
    saying why. Never raises: an unexpected failure is itself a refusal.

    ``param_policies`` is ``{placeholder_index (0-based): rule_name}``, the
    declared owner-side policy that may admit an otherwise-unsafe ``?`` (R7).
    ``schema_conn`` must be a dedicated connection (see ``_audit_reads``)."""
    try:
        return _classify(sql, schema_conn, param_policies or {})
    except Exception as exc:  # fail closed, always
        return _incomplete(f"classifier error: {type(exc).__name__}: {exc}")


def _classify(sql: str, conn: sqlite3.Connection, policies: Mapping[int, str]) -> Optional[Rejected]:
    if not isinstance(sql, str):
        return _incomplete("statement is not a str")
    # R6d -- the lexer must be able to place every construct.
    try:
        toks = _tokenize(sql)
    except _TokenizeError as exc:
        return _incomplete(f"tokenizer failure: {exc}")
    # R6c -- only anonymous '?' is admitted.
    for t in toks:
        if t.kind in ("param_numbered", "param_named"):
            return _incomplete(f"named or numbered parameter {t.text!r} at offset {t.pos}")
    # R7 -- each '?' by the token before it; closed safe set, default-deny.
    # Decided from the lexer alone, so it runs BEFORE the engine probes: a
    # statement the engine cannot even prepare (`title COLLATE ?` is a
    # syntax error) is still reported as the unsafe placeholder it is --
    # tests/test_engramd_read_registry.py::test_r7_every_other_placeholder_is_refused
    # pins that order. Every statement must pass both halves regardless.
    ordinal = {ti: k for k, ti in enumerate(i for i, x in enumerate(toks) if x.kind == "param")}
    placeholder_i = 0
    for idx, t in enumerate(toks):
        if t.kind != "param":
            continue
        prev = toks[idx - 1] if idx > 0 else None
        safe = (
            (prev is not None and prev.kind == "op" and prev.text in SAFE_PLACEHOLDER_OPERATORS)
            or _exact_json_each_form_at(sql, t.pos)
        )
        policy = policies.get(placeholder_i)
        n_th = placeholder_i + 1
        if policy is not None and policy not in PARAM_RULES:
            return Rejected(reason="unsafe_placeholder",
                            detail=f"placeholder {n_th}: unknown policy {policy!r}",
                            remedy=_REMEDY_REGISTER)
        if not safe and policy is None:
            before = prev.text if prev is not None else "<start of statement>"
            return Rejected(reason="unsafe_placeholder",
                            detail=f"placeholder {n_th} is preceded by {before!r}",
                            remedy="declare an owner-side parameter policy for this placeholder, "
                            "or use a typed read operation")
        context_ok = PARAM_RULE_CONTEXTS[policy] if policy is not None else None
        if context_ok is not None and not context_ok(toks, idx, ordinal, policies):
            return Rejected(reason="policy_template_mismatch",
                            detail=f"placeholder {n_th}: policy {policy!r} requires "
                            f"{_CONTEXT_REQUIRES[policy]}",
                            remedy="write the template in the form the policy assumes, or drop the policy")
        placeholder_i += 1
    for idx in policies:
        if not isinstance(idx, int) or not (0 <= idx < placeholder_i):
            return Rejected(reason="unsafe_placeholder",
                            detail=f"policy declared for placeholder index {idx!r}, "
                            f"but the statement has {placeholder_i}",
                            remedy=_REMEDY_REGISTER)
    # R6a -- scanner count vs ENGINE count.
    try:
        scanner_count = _scanner_placeholder_count(sql)
    except _TokenizeError as exc:
        return _incomplete(f"tokenizer failure: {exc}")
    try:
        engine_count = _engine_param_count(sql, conn, scanner_count)
    except sqlite3.Error as exc:
        return _incomplete(f"engine could not prepare the statement: {type(exc).__name__}: {exc}")
    if engine_count is None:
        return _incomplete("parameter count: no bound-value count satisfies the engine "
                           "(more than one statement, or an uncountable parameter)")
    if engine_count != scanner_count:
        return _incomplete(f"parameter count disagrees: scanner counts {scanner_count}, "
                           f"engine counts {engine_count}")
    # R5(i) / R6b -- audit the reads, then place every one.
    try:
        reads = _audit_reads(sql, conn)
    except sqlite3.Error as exc:
        return _incomplete(f"engine could not audit the statement: {type(exc).__name__}: {exc}")
    main, virtual, shadowing = _schema_catalog(conn)

    form_params = [t for t in toks if t.kind == "param" and _exact_json_each_form_at(sql, t.pos)]
    je_words = [t for t in toks
                if t.kind in ("word", "qident")
                and t.text.strip('"`[]').lower() in ("json_each", "json_tree")]
    json_each_ok = bool(form_params) and len(je_words) == len(form_params) and all(
        w.text.strip('"`[]').lower() == "json_each" for w in je_words)

    for table, _col, db_name, via in reads:
        if not table:
            return _incomplete("a read with an empty table name cannot be placed")
        low = str(table).lower()
        if low in ("json_each", "json_tree") and low not in main:
            if low == "json_each" and json_each_ok:
                continue
            return _incomplete(f"{table} appears outside the exact form {JSON_EACH_FORM!r}")
        if db_name is not None and db_name != "main":
            return _incomplete(f"read of {table!r} in non-main database {db_name!r}")
        if low not in main:
            return _incomplete(f"read of {table!r} cannot be placed in sqlite_master")
        # Accepting an unqualified (db_name None) read is sound ONLY while the
        # client-read connection's authorizer denies creating temp and attached
        # objects: a request-time shadow of a main table is then impossible.
        # Widening U4b's authorizer to allow temp objects makes this unsound.
        if db_name is None and low in shadowing:
            return _incomplete(f"read of {table!r} is ambiguous with a temp/attached object")
        if low in virtual or any(low.startswith(v + "_") for v in virtual):
            return Rejected(
                reason="virtual_table_template",
                detail=str(table),
                remedy="templates over virtual tables (FTS5, vec0) are not registrable; "
                "use a typed read operation",
            )
    return None


