_INT64_MIN, _INT64_MAX = -(2 ** 63), 2 ** 63 - 1


def _is_bindable(value) -> bool:
    """True for exactly the values sqlite3 can bind: None, bool, int within
    int64, float, str, bytes. Does not look inside str/bytes content."""
    if isinstance(value, str):
        try:
            value.encode("utf-8")  # a lone surrogate cannot be bound
        except UnicodeEncodeError:
            return False
        return True
    if value is None or isinstance(value, (bool, float, bytes)):
        return True
    if isinstance(value, int):
        return _INT64_MIN <= value <= _INT64_MAX
    return False


class Registry:
    """Immutable: ``templates`` is a read-only view, and the class has no
    mutating method (R3). Registration happens only through
    ``build_registry`` / ``load_registry`` (build-time path) or, on a
    ``DynamicRegistry`` in a dev install, ``register_dynamic`` (R4)."""

    __slots__ = ("_templates", "_refused", "_policies", "_nparams", "__weakref__")

    def __init__(self, templates, refused, policies, nparams) -> None:
        self._templates: Dict[str, str] = dict(templates)
        self._refused: Dict[str, Rejected] = dict(refused)
        self._policies: Dict[str, Dict[int, str]] = {k: dict(v) for k, v in policies.items()}
        self._nparams: Dict[str, int] = dict(nparams)

    @property
    def templates(self) -> Mapping[str, str]:
        """key -> sql, read-only (``types.MappingProxyType``)."""
        return types.MappingProxyType(self._templates)

    @property
    def refused(self) -> Mapping[str, Rejected]:
        """sql -> the refusal it received at registration."""
        return types.MappingProxyType(self._refused)

    def check(self, sql, params) -> Optional[Rejected]:
        """Admit (None) or refuse (``Rejected``) a request: lookup by exact
        bytes (R1), then parameter count, then the declared validators
        (R8). A refusal means nothing was prepared (R2)."""
        if not isinstance(sql, str):
            return Rejected(reason="invalid_read_request",
                            detail=f"sql must be a str, got {type(sql).__name__}",
                            remedy="send the registered statement text as a str")
        try:
            key = template_key(sql)
        except UnicodeEncodeError:
            return Rejected(reason="invalid_read_request",
                            detail="sql is not encodable as UTF-8",
                            remedy="send the registered statement text as a str")
        if self._templates.get(key) != sql:
            dropped = self._refused.get(sql)
            if dropped is not None:
                # #3753: listed, but the loader dropped it at load (re-classification against the
                # live store failed). The cause is the store, not the list: say so, carrying the
                # original reason as the detail so a caller can tell "your store lacks table X"
                # from "your owner is older than your hook" (`unregistered_template`).
                return Rejected(reason="refused_at_load", detail=dropped.reason,
                                remedy=f"{_REMEDY_REFUSED_AT_LOAD} (original remedy: {dropped.remedy})"
                                if dropped.remedy else _REMEDY_REFUSED_AT_LOAD)
            return Rejected(reason="unregistered_template", detail=key, remedy=_REMEDY_REGISTER)
        if not isinstance(params, (tuple, list)):
            return Rejected(reason="invalid_parameter",
                            detail=f"params must be a tuple or list, got {type(params).__name__}",
                            remedy="send the positional parameters as a list")
        expected = self._nparams[key]
        if len(params) != expected:
            return Rejected(reason="invalid_parameter",
                            detail=f"expected {expected} parameters, got {len(params)}",
                            remedy="send exactly the registered number of parameters")
        for idx, value in enumerate(params):
            if not _is_bindable(value):
                return Rejected(reason="invalid_parameter",
                                detail=f"parameter {idx + 1}: unbindable type {type(value).__name__}",
                                remedy="send only None, bool, int (within int64), float, str or bytes")
        for idx, rule in sorted(self._policies.get(key, {}).items()):
            validator = PARAM_RULES[rule]
            try:
                validator(params[idx])
            except ParamRejected as exc:
                return Rejected(reason="invalid_parameter", detail=rule,
                                remedy=f"parameter {idx + 1} refused by rule {rule}: {exc}")
        return None


class DynamicRegistry(Registry):
    """R4: a registry that additionally accepts ``register_dynamic``. Only
    constructible through ``build_registry(..., dynamic=True)``, which the
    owner reaches only after ``resolve_dynamic_flag`` approved a dev tier."""

    __slots__ = ("_schema_conn",)

    def __init__(self, templates, refused, policies, nparams, schema_conn) -> None:
        super().__init__(templates, refused, policies, nparams)
        self._schema_conn = schema_conn

    def register_dynamic(self, sql, param_policies: Optional[Mapping[int, str]] = None) -> Optional[Rejected]:
        """Classify and register ``sql`` at runtime. EVERY call logs one
        WARNING naming the template key. Classification (R5-R7) still runs."""
        key = template_key(sql) if isinstance(sql, str) else "<non-str>"
        _log.warning("dynamic template registration (dev tier only): key=%s", key)
        refusal = classify_template(sql, self._schema_conn, param_policies)
        if refusal is not None:
            return refusal
        self._templates[key] = sql
        self._nparams[key] = _scanner_placeholder_count(sql)
        if param_policies:
            self._policies[key] = dict(param_policies)
        return None


def build_registry(
    templates: Iterable[str],
    schema_conn: sqlite3.Connection,
    param_policies: Optional[Mapping[str, Mapping[int, str]]] = None,
    *,
    dynamic: bool = False,
) -> Registry:
    """The build-time registration path: classify each template against
    ``schema_conn`` and admit the ones that pass. Refusals are kept in
    ``.refused`` (sql -> Rejected)."""
    param_policies = param_policies or {}
    admitted: Dict[str, str] = {}
    refused: Dict[str, Rejected] = {}
    policies: Dict[str, Dict[int, str]] = {}
    nparams: Dict[str, int] = {}
    for sql in templates:
        if not isinstance(sql, str):
            _log.warning("ignoring non-str template of type %s", type(sql).__name__)
            continue
        pol = param_policies.get(sql)
        refusal = classify_template(sql, schema_conn, pol)
        if refusal is not None:
            refused[sql] = refusal
            continue
        key = template_key(sql)
        admitted[key] = sql
        nparams[key] = _scanner_placeholder_count(sql)
        if pol:
            policies[key] = dict(pol)
    if dynamic:
        return DynamicRegistry(admitted, refused, policies, nparams, schema_conn)
    return Registry(admitted, refused, policies, nparams)


#: Refuses everything. What a gate built without a registry holds, and what
#: every load failure degrades to (R12).
EMPTY_REGISTRY = Registry({}, {}, {}, {})


# ---------------------------------------------------------------------------
# R4: the escape hatch's resolution
# ---------------------------------------------------------------------------


def resolve_dynamic_flag(env: Mapping[str, str], install_tier: Optional[str]) -> bool:
    """True iff ``ENGRAM_OWNER_ALLOW_DYNAMIC_TEMPLATES`` is exactly ``"1"``
    AND the install tier is ``dev``. Any other value counts as unset. The
    flag set to ``"1"`` on any non-dev tier raises ``DynamicTemplatesRefused``
    -- the caller (the owner's ``start()``) does this BEFORE binding the
    socket."""
    if env.get(DYNAMIC_FLAG_ENV) != "1":
        return False
    if install_tier != "dev":
        raise DynamicTemplatesRefused(
            f"{DYNAMIC_FLAG_ENV}=1 is only honoured on a dev install "
            f"(install_tier={install_tier!r}); refusing to start"
        )
    return True


# ---------------------------------------------------------------------------
# R12: the loader -- a bad file means an EMPTY registry, never a permissive one
# ---------------------------------------------------------------------------


def load_registry(path, schema_conn: sqlite3.Connection, *, dynamic: bool = False) -> Registry:
    """Load the committed template list. Missing / unreadable / malformed /
    schema-mismatched file -> an EMPTY registry. Every listed template is
    re-classified against ``schema_conn`` (the LIVE store's schema); one that
    fails, or whose listed key does not match its SQL, is dropped with ONE
    log line."""
    empty = build_registry([], schema_conn, dynamic=True) if dynamic else EMPTY_REGISTRY
    try:
        with open(path, "r", encoding="utf-8") as fh:
            data = json.load(fh)
    except (OSError, ValueError) as exc:
        _log.warning("read-template file %s unusable (%s: %s); registry is EMPTY",
                     path, type(exc).__name__, exc)
        return empty
    if not isinstance(data, dict) or data.get("schema") != SCHEMA_VERSION \
            or not isinstance(data.get("templates", []), list):
        _log.warning("read-template file %s has an unexpected shape or schema; registry is EMPTY", path)
        return empty
    wanted: List[str] = []
    for entry in data.get("templates", []):
        sql = entry.get("sql") if isinstance(entry, dict) else None
        key = entry.get("key") if isinstance(entry, dict) else None
        if not isinstance(sql, str) or not isinstance(key, str):
            _log.warning("dropping malformed template entry %r", entry)
            continue
        if key != template_key(sql):
            _log.warning("dropping template %s: listed key does not match the sha256 of its sql", key)
            continue
        wanted.append(sql)
    reg = build_registry(wanted, schema_conn, dynamic=dynamic)
    for sql, why in reg.refused.items():
        _log.warning("dropping template %s: %s (%s)", template_key(sql), why.reason, why.detail)
    return reg
