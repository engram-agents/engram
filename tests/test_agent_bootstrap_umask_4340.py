"""#4340 (A): umask 027 above the interactive guard of agent-bootstrap's .bashrc skeleton,
and UMask=0027 in the owner unit template.

Contract (written before the code):
  C1  the generated .bashrc, sourced by a NON-interactive shell (BASH_ENV, no PS1), yields 0027
  C2  control: the same harness on today's skeleton (umask below the guard) yields 0022, so C1
      can fail
  C3  an interactive shell (PS1 set) that sources it still yields 0027
  C4  the rest of the skeleton is unchanged (only the umask line moves, one comment line is added)
  C5  the owner unit template carries exactly one real `UMask=0027` line inside [Service]
  C6  control: the same parser rejects the line in [Unit] and the line commented out
  C7  tools/agentctl and the .runtime/start.sh heredoc are byte-identical to origin/dev

Scope: shells that source ~/.bashrc non-interactively, and the owner unit. NOT the Claude
process, hooks or fairies: their umask comes from the launch prologue in tools/agentctl, which
this change does not touch (item B of #4340).
"""
from __future__ import annotations

import re
import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
BOOTSTRAP = REPO / "tools" / "agent-bootstrap"
TEMPLATE = REPO / "src" / "engram" / "templates" / "engramd-owner.service.template"

BASHRC_OPEN = 'cat >"$USER_HOME/.bashrc" <<\'BASHRC\'\n'
RUN_OPEN = 'cat >"$USER_HOME/.runtime/start.sh" <<\'RUN\'\n'

OLD_UMASK_LINE = "umask 027                                    # group-readable but not world\n"
# Verbatim copy of the heredoc body BEFORE #4340 (umask below the interactive guard).
OLD_BASHRC = (
    "# Skeletal .bashrc for AI agent runtime.\n"
    "# Generated by agent-bootstrap. The operator may edit.\n"
    "#\n"
    "# IMPORTANT: do NOT add `export ANTHROPIC_API_KEY=...` or\n"
    "# `export GOOGLE_API_KEY=...` here. Headless CLI calls will silently\n"
    "# route to a metered API tier instead of the OAuth Max subscription\n"
    "# pool (billing-leak guard — never let a co-located agent inherit another's API key).\n"
    '[ -z "$PS1" ] && return\n'
    'export PATH="$HOME/.local/bin:$PATH"\n'
    'export ENGRAM_HOME="$HOME/.engram"          # explicit, no fallback\n'
    + OLD_UMASK_LINE
    + "PS1='\\[\\e[1;33m\\]\\u@\\h\\[\\e[0m\\]:\\[\\e[1;34m\\]\\w\\[\\e[0m\\]\\$ '\n"
)


def _heredoc(text: str, opener: str, terminator: str) -> str:
    assert text.count(opener) == 1, f"opener {opener!r} must appear exactly once"
    lines = text.split(opener, 1)[1].splitlines(keepends=True)
    ends = [i for i, ln in enumerate(lines) if ln == terminator + "\n"]
    assert len(ends) >= 1, f"terminator {terminator!r} not found"
    return "".join(lines[: ends[0]])


def _marker_lines_exactly_once(text: str) -> None:
    assert sum(1 for ln in text.splitlines() if ln == "BASHRC") == 1, "BASHRC terminator count"


def _bashrc_now() -> str:
    text = BOOTSTRAP.read_text()
    _marker_lines_exactly_once(text)
    return _heredoc(text, BASHRC_OPEN, "BASHRC")


def _noninteractive_umask(tmp_path: Path, bashrc: str) -> str:
    rc = tmp_path / ".bashrc"
    rc.write_text(bashrc)
    p = subprocess.run(
        ["env", "-i", f"HOME={tmp_path}", f"BASH_ENV={rc}", "bash", "-c", "umask"],
        capture_output=True, text=True, timeout=30,
    )
    assert p.returncode == 0, p.stderr
    return p.stdout.strip()


def test_c1_noninteractive_shell_sourcing_the_generated_bashrc_gets_0027(tmp_path):
    assert _noninteractive_umask(tmp_path, _bashrc_now()) == "0027"


def test_c2_control_todays_skeleton_gives_0022_under_the_same_harness(tmp_path):
    assert _noninteractive_umask(tmp_path, OLD_BASHRC) == "0022"


def test_c3_interactive_shell_still_gets_0027(tmp_path):
    rc = tmp_path / ".bashrc"
    rc.write_text(_bashrc_now())
    p = subprocess.run(
        # bash unsets an inherited PS1 in a non-interactive shell, so PS1 is set inside the
        # script, just before sourcing: that is what an interactive shell looks like to the guard.
        ["env", "-i", f"HOME={tmp_path}", "bash", "--norc", "-c", f"PS1=x; . {rc}; umask"],
        capture_output=True, text=True, timeout=30,
    )
    assert p.returncode == 0, p.stderr
    assert p.stdout.strip() == "0027"


def test_c4_rest_of_skeleton_unchanged():
    lines = _bashrc_now().splitlines(keepends=True)
    idx = [i for i, ln in enumerate(lines) if ln.startswith("umask 027")]
    assert len(idx) == 1
    i = idx[0]
    assert lines[i - 1].startswith("#"), "the why-above-the-guard comment line is missing"
    remaining = "".join(lines[: i - 1] + lines[i + 1:])
    assert remaining == OLD_BASHRC.replace(OLD_UMASK_LINE, "", 1)


def _service_umask_state(text: str) -> str:
    """'ok' iff exactly one non-comment `UMask=0027` line exists, and it is inside [Service]."""
    section = None
    hits: dict = {}
    for raw in text.splitlines():
        line = raw.strip()
        m = re.fullmatch(r"\[([A-Za-z]+)\]", line)
        if m:
            section = m.group(1)
        elif line.startswith("UMask="):
            key = section if line == "UMask=0027" else f"{section}:wrong-value"
            hits[key] = hits.get(key, 0) + 1
    return "ok" if hits == {"Service": 1} else "not in [Service]"


def _template_without_umask() -> str:
    return "".join(ln for ln in TEMPLATE.read_text().splitlines(keepends=True)
                   if ln.strip() != "UMask=0027")


def test_c5_owner_unit_has_one_real_umask_in_service():
    assert _service_umask_state(TEMPLATE.read_text()) == "ok"


def test_c6_control_parser_rejects_unit_section_and_commented_line():
    base = _template_without_umask()
    assert "[Unit]\n" in base and "[Service]\n" in base
    in_unit = base.replace("[Unit]\n", "[Unit]\nUMask=0027\n", 1)
    commented = base.replace("[Service]\n", "[Service]\n# UMask=0027\n", 1)
    assert "UMask=0027" in in_unit and "UMask=0027" in commented
    assert _service_umask_state(in_unit) == "not in [Service]"
    assert _service_umask_state(commented) == "not in [Service]"
    assert _service_umask_state(base) == "not in [Service]"
    assert _service_umask_state(base.replace("[Service]\n", "[Service]\nUMask=0027\n", 1)) == "ok"


def test_c7_untouched_surfaces_are_byte_identical_to_origin_dev():
    d = subprocess.run(["git", "diff", "origin/dev", "--", "tools/agentctl"],
                       cwd=REPO, capture_output=True, text=True, timeout=60)
    assert d.returncode == 0, d.stderr
    assert d.stdout == ""
    base = subprocess.run(["git", "show", "origin/dev:tools/agent-bootstrap"],
                          cwd=REPO, capture_output=True, text=True, timeout=60)
    assert base.returncode == 0, base.stderr
    assert (_heredoc(BOOTSTRAP.read_text(), RUN_OPEN, "RUN")
            == _heredoc(base.stdout, RUN_OPEN, "RUN"))
